open Util
open Primitive

let flip = Fun.flip
let ( @> ) = Snoc.( @> )

let fresh_i =
  let i = ref (-1) in
  fun () ->
    incr i;
    !i

(* de bruijn indices and levels *)
type ix = int
type lvl = int
type mv = int

module MC = Map.Make (Int)
module TC = Map.Make (String)

(* bound or defined variables *)
type bd =
  | B
  | D

(*NOTE: removed location tracking, might be useful to keep it *)
(* core syntax, tms *)
type tm =
  | Local of string * ix (* local variable as de bruijn index *)
  | Top of string (* reference to a top level function *)
  | Ap of binder * tm * tm
  | Mv of mv
  | IMv of mv * bd Snoc.t (* generated mv *)
  | Tuple of tm list
  | Let of string * tm * tm * tm (* let p₁ ... pₙ : type = e₁ in e₂ *)
  | Match of tm * (located_pattern * tm * tm) list
    (* match cond to | p₁ when x₁ => y₁ ... | pₙ when xₙ => yₙ*)
  | Lam of string * tm
  | Const of const
  | TypeLit of prim
  | Pi of string * tm * tm (* (α : β) -> γ *)

(* values for NbE *)
and val_ =
  | VLam of string * closure
  | VTop of string * spine (* equivalent of a top in tm *)
  | VRigid of string * lvl * spine (* value equivalent of local in tm *)
  | VFlex of mv * spine (* value equivalent of a metavariable in tm *)
  | VTuple of val_ list
  | VMatch of val_ * env * (located_pattern * tm * tm) list
  | VPi of string * val_ * closure
  | VTypeLit of prim
  | VConst of const

and env = val_ Snoc.t

(* list of variables that a mv or local is applied to *)
and spine = val_ Snoc.t

(* is the mv solved or unsolved? *)
and mv_entry =
  | Solved of val_
  | Unsolved

(* local variables in lambdas *)
and closure = env * tm

(* top level extras *)
type located_ty_decl = Location.t * ty_decl
and ty_decl = string * tdecl_type

and tdecl_type =
  | Alias of tm
  | Variant of tm * (string * tm) list
  | Record of string * tm * (string * tm) list

type located_definition = Location.t * definition
and definition = tm * string * tm * tm
(* type, identifer, optional when-block, body, optional with-block *)

type program =
  string * located_import list * located_ty_decl list * located_definition list

let mctx : mv_entry MC.t ref = ref MC.empty

(* shouldn't fail, all mvs are either generated by the compiler or by the user
   through holes and would be tracked *)
let lookup_mv (m : mv) : mv_entry = MC.find m !mctx

(* generate an unsolved meta variable *)
let gen_mv bds : tm =
  let mv = fresh_i () in
  mctx := MC.add mv Unsolved !mctx;
  IMv (mv, bds)

(* early declaration of val/tm for errors *)
let rec pp_tm out (tm : tm) =
  match tm with
  | Local (i, _) | Top i -> Format.fprintf out "%s" i
  | Const c -> pp_const out c
  | TypeLit p -> pp_prim out p
  | Ap (_, f, arg) ->
    Format.fprintf out "(@[<hov>%a@ %@ %a@])" pp_tm f pp_tm arg
  | Tuple t ->
    Format.fprintf out "(@[<hov>%a@])"
      Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out ",@ ") pp_tm)
      t
  | Let (p, ty, v, n) ->
    Format.fprintf out "@[<v 2>let %s : %a =@,%a@]@,in@,%a" p pp_tm ty pp_tm v
      pp_tm n
  | Lam (arg, body) -> Format.fprintf out "\\@[<v 2> %s. {@,%a@,}@]" arg pp_tm body
  | Match (c, bs) ->
    let pp_branch out (p, wb, b) =
      Format.fprintf out "(wh@[<v>en %a)@,(%a) ⇒ %a@]" pp_tm wb pp_pattern p
        pp_tm b
    in
    Format.fprintf out "ma@[<v>tch (%a)@,%a@]" pp_tm c
      Format.(pp_print_list ~pp_sep:pp_print_cut pp_branch)
      bs
  | Pi (n, l, r) -> Format.fprintf out "@[<v>(%s : %a) -> %a@]" n pp_tm l pp_tm r
  | Mv m -> Format.fprintf out "?meta%d" m
  | IMv (m, bds) ->
    let to_str bd =
      match bd with
      | B -> "b"
      | D -> "d"
    in
    Format.fprintf out "?meta%d (%s)" m
      (Snoc.map to_str bds
      |> Snoc.fold_left (fun acc v -> Printf.sprintf "%s %s" v acc) "")

let rec pp_val out (v : val_) =
  match v with
  | VTypeLit p -> pp_prim out p
  | VConst c -> pp_const out c
  | VTop (i, sp) -> Format.fprintf out "%s (%s)" i (pp_sp pp_val sp)
  | VLam (p, cl) -> Format.fprintf out "\\@[<v> %s. {@,%a@]@,}" p pp_closure cl
  | VTuple vs ->
    Format.fprintf out "(%a)"
      Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out ",@ ") pp_val)
      vs
  | VMatch (c, _, bs) ->
    let pp_branch out (p, wb, b) =
      Format.fprintf out "(wh@[<v>en %a)@,(%a) ⇒ %a@]" pp_tm wb pp_pattern p
        pp_tm b
    in
    Format.fprintf out "ma@[<v>tch (%a)@,%a@]" pp_val c
      Format.(pp_print_list ~pp_sep:pp_print_cut pp_branch)
      bs
  | VPi (n, l, cl) ->
    Format.fprintf out "(%s : %a) -> %a" n pp_val l pp_closure cl
  | VRigid (i, _, sp) -> Format.fprintf out "%s (%s)" i (pp_sp pp_val sp)
  | VFlex (m, sp) -> Format.fprintf out "?meta%d (%s)" m (pp_sp pp_val sp)

and pp_sp pp_func s =
  let open Snoc in
  let rec go = function
    | Lin -> ""
    | Snoc (Lin, x) -> Format.asprintf "%a" pp_func x
    | Snoc (xs, x) -> Format.asprintf "%a; %s" pp_func x (go xs)
  in
  go s

and pp_closure out ((env, tm) : closure) =
  Format.fprintf out "[ @[<v>%s ] -> @,%a@]" (pp_sp pp_val env) pp_tm tm

(* term → val *)
let rec to_val (env : env) (tm : tm) : val_ =
  match tm with
  | Local (n, i) ->
    Log.dbg None (Format.asprintf "@[<v>indexing %s with %d into env.@,env ↦ [ %s ]@]" n i (pp_sp pp_val env));
    Snoc.nth env i (*NOTE: shouldn't fail unless code is buggy *)
  | TypeLit p -> VTypeLit p
  | Const c -> VConst c
  | Top i -> VTop (i, Snoc.empty)
  | Tuple ts -> VTuple (List.map (to_val env) ts)
  | Lam (p, t) -> VLam (p, (env, t))
  | Pi (n, l, r) -> VPi (n, to_val env l, (env, r))
  | Ap (_, l, r) -> v_ap (to_val env l) (to_val env r)
  | Mv m -> v_meta m
  | IMv (m, bds) -> v_ap_bds env bds (v_meta m)
  | Match (c, bs) ->
    let c = to_val env c in
    VMatch (c, env, bs)
  | Let (_, _, v, n) -> to_val (env @> to_val env v) n

(*
   applies a closure to a value and evaluates it pretty much β-reduction.
*)
and ( $$ ) ((env, t) : closure) (v : val_) : val_ = to_val (env @> v) t

and v_ap l r =
  match l with
  | VLam (_, t) -> t $$ r
  | VFlex (m, sp) -> VFlex (m, sp @> r)
  | VRigid (i, lvl, sp) -> VRigid (i, lvl, sp @> r)
  | VTop (i, sp) -> VTop (i, sp @> r)
  | _ ->
    raise
      (Error.InternalError "Internal Error - called `v_ap` on non-function.")

(* unroll a spine *)
and v_ap_sp spine v =
  match spine with
  | Snoc.Lin -> v
  | Snoc.Snoc (spvs, s) -> v_ap (v_ap_sp spvs v) s

and v_meta m =
  match MC.find m !mctx with
  | Solved v -> v
  | Unsolved -> VFlex (m, Snoc.empty)

and v_ap_bds env bds m =
  match (env, bds) with
  | Lin, Lin -> m
  | Snoc (env, e), Snoc (bds, bd) -> (
    match bd with
    | B -> v_ap (v_ap_bds env bds m) e
    | D -> v_ap_bds env bds m)
  | _ -> raise (Error.InternalError "Internal Error - mismatched env/bds list.")

(* reduce a metavariable if possible *)
let force = function
  | VFlex (m, sp) as flex -> (
    match lookup_mv m with
    | Solved v -> 
      Log.dbg None (Format.asprintf "pulled solution from mctx := %a@." pp_val v);
      let v = v_ap_sp sp v in
      Log.dbg None (Format.asprintf "vapsp solution from mctx := %a@." pp_val v);
      v
    | Unsolved -> flex)
  | v -> v

(* mutable list that holds all of the holes found in source code *)
let holes : (Location.t * val_) list ref = ref []

(* push a hole into the list *)
let add_hole v = holes := v :: !holes

(* format the list of holes *)
let fmt_holes () =
  let pp_hole out (loc, v) =
    let v = force v in
    Format.fprintf out "%a ⇒ %a" Location.pp_location loc pp_val v
  in
  Format.asprintf "Fo@[<v 2>und typed hole(s):@,%a@]"
    Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out "@,") pp_hole)
    !holes

(* db level → db index *)
let to_ix (l : lvl) (r : lvl) = l - r - 1

(* val → tm *)
let rec quote (lvl : lvl) (v : val_) : tm =
  match force v with
  | VTypeLit t -> TypeLit t
  | VConst c -> Const c
  | VTop (i, sp) -> quote_sp lvl (Top i) sp
  | VTuple vs -> Tuple (List.map (quote lvl) vs)
  | VMatch (c, env, bs) ->
    let c = quote lvl c in
    let quote_b env (p, wb, b) =
      let rec build_env env (_, p) l =
        match p with
        | PWild | PTypeLit _ | PConst _ -> env, l
        | PVar i -> (env @> VRigid (i, l, Snoc.empty)), l + 1
        | PTuple ps ->
          let ps, l =
            List.fold_left
              (fun (sn, l) n -> let sn, l = build_env sn n l in sn, l + 1)
              (env, l)
              ps
          in ps, l
        | PCtor (_, args) ->
          let args, l =
            List.fold_left
              (fun (sn, l) n -> let sn, l = build_env sn n l in sn, l + 1)
              (env, l)
              args
          in args, l + Snoc.length args
          (* adding arg length is kinda sus *)
      in
      let env, l = build_env env p lvl in
      let wb = to_val env wb |> quote l in
      let b = to_val env b |> quote l in
      p, wb, b
    in
    let bs = List.map (quote_b env) bs in
    Match (c, bs)
  | VLam (p, cl) ->
    (*
       increment the level as we move into the closure add a local with the
       current level to capture the current argument
    *)
    Lam (p, quote (lvl + 1) (cl $$ VRigid (p, lvl, Snoc.empty)))
  | VPi (n, l, cl) ->
    let l = quote lvl l in
    let r = quote (lvl + 1) (cl $$ VRigid (n, lvl, Snoc.empty)) in
    Pi (n, l, r)
  | VFlex (m, sp) -> quote_sp lvl (Mv m) sp
  | VRigid (i, l, sp) -> quote_sp lvl (Local (i, to_ix lvl l)) sp

(* unroll a flex/rigid into a set of applications *)
and quote_sp (lvl : lvl) (v : tm) (sp : spine) : tm =
  match sp with
  | Snoc.Lin -> v
  | Snoc.Snoc (sp, s) -> Ap (0, quote_sp lvl v sp, quote lvl s)

(* type checking *)
type 'a result = 'a Base.Or_error.t

let ( let* ) = Base.Or_error.( >>= )
let ( let@ ) = Base.Or_error.( >>| )
let ok (v : 'a) : 'a result = Ok v

let make_err (e : Error.t) : 'a result =
  Base.Or_error.error_string @@ Error.format_err e

let ( <|> ) l r ctx =
  match l ctx with
  | Ok _ as v -> v
  | Error _ -> r ctx

let combine_errors = Base.Or_error.combine_errors
let combine_errors_unit = Base.Or_error.combine_errors_unit

(*
   partial renaming. the solution to a problem like ?α spine =? t is ?α = λ x₁
   ... xₙ . t, where the solution has a context Δ and the spine has a context Γ.
   we need to rename spine locals so that they're valid within the Δ context,
   which is where partial renaming comes in.
*)
type partial = {
  gamma : lvl;
  delta : lvl;
  subs : lvl MC.t;
}

let extend_pn (p : partial) : partial =
  {
    gamma = p.gamma + 1;
    delta = p.delta + 1;
    subs = MC.add p.gamma p.delta p.subs;
  }

(* computes Γ ↦ Δ *)
let invert_mapping (loc : Location.t) (delta : lvl) (sp : spine) :
    partial result =
  let open Snoc in
  let rec go = function
    | Lin -> ok @@ (0, MC.empty)
    | Snoc (sp, s) -> (
      let* gamma, subs = go sp in
      match force s with
      | VRigid (_, l, Snoc.Lin) -> (
        match MC.mem l subs with
        | true ->
          make_err
            (Some loc, "Non-linear bound variable in unification problem.")
        | false -> ok (gamma + 1, MC.add l gamma subs))
      | _ -> make_err (Some loc, "Unbound value in unification problem."))
  in
  let@ gamma, subs = go sp in
  {gamma; delta; subs}

let rename (loc : Location.t) (mv : mv) (p : partial) (v : val_) : tm result =
  let rec go_sp p sp v : tm result =
    let open Snoc in
    match sp with
    | Lin -> ok v
    | Snoc (sp, s) ->
      let* l = go_sp p sp v in
      let@ r = go p s in
      Ap (0, l, r)
  and go p v : tm result =
    match force v with
    | VFlex (mv', sp) ->
      if mv = mv' then
        make_err (Some loc, "Found infinite type in unification problem.")
      else
        go_sp p sp (Mv mv')
    | VRigid (i, l, sp) -> (
      match MC.find_opt l p.subs with
      | None ->
        Log.dbg None (Format.asprintf "rigid(%d) -> %a@.subs -> %d@." l pp_val (force v) (MC.to_list p.subs |> List.length));
        make_err (Some loc, Printf.sprintf "Variable '%s' escapes scope." i)
      | Some l -> go_sp p sp (Local (i, to_ix p.gamma l)))
    | VLam (a, cl) ->
      let@ b = go (extend_pn p) (cl $$ VRigid (a, p.delta, Snoc.empty)) in
      Lam (a, b)
    | VPi (n, l, cl) ->
      let* l = go p l in
      let@ r = go (extend_pn p) (cl $$ VRigid (n, p.delta, Snoc.empty)) in
      Pi (n, l, r)
    | VMatch (c, env, bs) ->
      let* c = go p c in
      let@ bs =
        List.map
          (fun (pat, wb, b) ->
            let* wb = to_val env wb |> go p in
            let@ b = to_val env b |> go p in
            (pat, wb, b))
          bs
        |> combine_errors
      in
      Match (c, bs)
    | VTuple vs ->
      let@ vs = List.map (go p) vs |> combine_errors in
      Tuple vs
    | VConst c -> ok @@ Const c
    | VTypeLit p -> ok @@ TypeLit p
    | VTop (i, sp) -> go_sp p sp (Top i)
  in
  go p v

let solve (loc : Location.t) (gamma : lvl) (mv : mv) (sp : spine) (rhs : val_) :
    unit result =
  let nest lvl v =
    let rec go n t acc =
      if n = acc then
        t
      else
        Lam ("x" ^ string_of_int (acc + 1), go n t (acc + 1))
    in
    go lvl v 0
  in
  let* p = invert_mapping loc gamma sp in
  Log.dbg None (Format.asprintf "rhs := %a@." pp_val rhs);
  let@ rhs = rename loc mv p rhs in
  let sol = to_val Snoc.empty @@ nest p.gamma rhs in
  mctx := MC.add mv (Solved sol) !mctx

(* record name, constructor, overall type, field name & type *)
type record_info = string * string * Ast.located_expr * (string * val_) list

type ctx = {
  env : env;
  top : top_entry TC.t;
  tys : (string * val_) Snoc.t;
  lvl : lvl;
  bds : bd Snoc.t;
}

and top_entry = {
  ty : val_;
  def : def;
}

and def =
  | Def of tm
  (* NOTE: 
     store variants as a None, records as a Some _.
     check later on (in RCons) that the pulled TCon is a Some _.
     then do whatever else
  *)
  | TCon of (string * val_) list option
  | DCon of tm (* overall type, constructor func *)
  | Axiom

let empty_ctx () =
  {
    env = Snoc.empty;
    top = TC.empty;
    tys = Snoc.empty;
    lvl = 0;
    bds = Snoc.empty;
  }

(* binding and defining local variables *)
let bind_var ~(id : string) ~(t : val_) (ctx : ctx) =
  {
    ctx with
    env = ctx.env @> VRigid (id, ctx.lvl, Snoc.empty);
    tys = ctx.tys @> (id, t);
    lvl = ctx.lvl + 1;
    bds = ctx.bds @> B;
  }

let define_var ~(id : string) ~(v : val_) ~(t : val_) (ctx : ctx) =
  {
    ctx with
    env = ctx.env @> v;
    tys = ctx.tys @> (id, t);
    lvl = ctx.lvl + 1;
    bds = ctx.bds @> D;
  }

(* binding and defining functions/type constructors *)
let bind_func ~(id : string) ~(t : val_) (ctx : ctx) =
  {ctx with top = TC.add id {ty = t; def = Axiom} ctx.top}

let define_func ~(id : string) ~(v : tm) ~(t : val_) (ctx : ctx) =
  {ctx with top = TC.add id {ty = t; def = Def v} ctx.top}

let define_dcon ~(id: string) ~(t: val_) ~(v: tm) (ctx : ctx) =
  {ctx with top = TC.add id {ty = t; def = DCon v} ctx.top}

let define_tcon ~(id: string) ~(t: val_) ~(fields: (string * val_) list option) (ctx: ctx) =
  {ctx with top = TC.add id {ty = t; def = TCon fields} ctx.top}

let lookup_top (i : string) (ctx : ctx) : (def * val_) option =
  match TC.find_opt i ctx.top with
  | Some top -> Some (top.def, top.ty)
  | None -> None

let uni_err loc pp_func ex got =
  make_err
    ( loc,
      Format.asprintf "Fa@[<v>iled to unify:@,Left: %a@,Right: %a@,@]" pp_func
        ex pp_func got )

let rec unify (loc : Location.t) (ctx : ctx) (l : val_) (r : val_) : unit result
    =
  let bump_lvl ctx = {ctx with lvl = ctx.lvl + 1} in
  let rec unify_sp ctx sp sp' =
    let open Snoc in
    match (sp, sp') with
    | Lin, Lin -> ok ()
    | Snoc (sp, s), Snoc (sp', s') ->
      let* _ = unify_sp ctx sp sp' in
      unify loc ctx s s'
    | _ -> make_err (Some loc, "Rigid mismatch in unification.")
  in
  match (force l, force r) with
  | VTypeLit l, VTypeLit r when l#=r -> ok ()
  | VConst l, VConst r when l %= r -> ok ()
  | VPi (n, l, cl), VPi (n', l', cl') ->
    (* go into the closure and check that the bound variables are equal *)
    let* _ = unify loc ctx l l' in
    unify loc (bump_lvl ctx)
      (cl $$ VRigid (n, ctx.lvl, Snoc.empty))
      (cl' $$ VRigid (n', ctx.lvl, Snoc.empty))
  | VLam (p, cl), VLam (p', cl') ->
    unify loc (bump_lvl ctx)
      (cl $$ VRigid (p, ctx.lvl, Snoc.empty))
      (cl' $$ VRigid (p', ctx.lvl, Snoc.empty))
  | VLam (p, cl), t | t, VLam (p, cl) ->
    (*
       check that applying the right to the captured variable is the same as
       going into the closure with the captured variable (fun x -> M x) N => M N
    *)
    unify loc (bump_lvl ctx)
      (cl $$ VRigid (p, ctx.lvl, Snoc.empty))
      (v_ap t (VRigid (p, ctx.lvl, Snoc.empty)))
  | VMatch (c, env, bs), VMatch (c', env', bs') when List.length bs = List.length bs' ->
    (*TODO: unify patterns *)
    let* _ = unify loc ctx c c' in
    List.map2 
      (fun (_, _, b) (_, _, b') -> 
        let b = to_val env b in
        let b' = to_val env' b' in
        unify loc ctx b b') 
      bs bs'
    |> combine_errors_unit
  | VRigid (_, ri, sp), VRigid (_, ri', sp') when ri = ri' ->
    unify_sp ctx sp sp'
  | VTop (i, sp), VTop (i', sp') when i = i' -> unify_sp ctx sp sp'
  | VTop (i, sp), t | t, VTop (i, sp) -> (
    match lookup_top i ctx with
    | None ->
      make_err (Some loc, Printf.sprintf "Undefined identifier - '%s'." i)
    | Some (Def b, _) ->
      let b = to_val Snoc.empty b |> v_ap_sp sp in
      unify loc ctx b t
    | Some (DCon _, t') | Some (TCon _, t') -> 
      unify loc ctx t' t
    | Some (Axiom, _) ->
      make_err
        (Some loc, Printf.sprintf "The function '%s' has no definition." i))
  | VFlex (mv, sp), VFlex (mv', sp') when mv = mv' -> unify_sp ctx sp sp'
  | VFlex (mv, sp), t | t, VFlex (mv, sp) -> 
    solve loc ctx.lvl mv sp t
  | l, r -> uni_err (Some loc) pp_val l r

let fresh_pattern_var () : string = "__p_" ^ (fresh_i () |> string_of_int)
let fresh_bind_var () : string = "__b_" ^ (fresh_i () |> string_of_int)

let replace_pattern ((_, p) : located_pattern)
    ((loc, _) as b : Ast.located_expr) : string * Ast.located_expr =
  match p with
  | PVar i -> (i, b)
  | _ ->
    (* we create a match expr to remove the pattern from the expression *)
    let i = fresh_pattern_var () in
    let match_ =
      let c = (loc, Ast.Var (Ident i)) in
      let branch = [((loc, p), None, b)] in
      (loc, Ast.Match (c, branch))
    in
    (i, match_)

let rec check (ctx : ctx) ((loc, e) : Ast.located_expr) (ex : val_) : tm result
    =
  match (e, force ex) with
  | Ast.Lam (p, b), VPi (_, l, cl) ->
    let i, b = replace_pattern p b in
    let@ b =
      check (bind_var ~id:i ~t:l ctx) b (cl $$ VRigid (i, ctx.lvl, Snoc.empty))
    in
    Lam (i, b)
  | Ast.Let (p, t, b, n), t' -> (
    let i, b = replace_pattern p b in
    match t with
    | Some t ->
      let* t, _ = is_type ctx t in
      let vt = to_val ctx.env t in
      let* b = check ctx b vt in
      let@ n = check (define_var ~id:i ~v:(to_val ctx.env b) ~t:vt ctx) n t' in
      Let (i, t, b, n)
    | None ->
      let* b, t = infer ctx b in
      let@ n = check (define_var ~id:i ~v:(to_val ctx.env b) ~t ctx) n t' in
      let t = quote ctx.lvl t in
      Let (i, t, b, n))
  | Ast.Hole, _ ->
    let v = gen_mv ctx.bds in
    add_hole (loc, to_val ctx.env v);
    ok v
  | e, ex ->
    let* e, t = infer ctx (loc, e) in
    let@ _ = unify loc ctx t ex in
    e

and infer (ctx : ctx) ((loc, e) : Ast.located_expr) : (tm * val_) result =
  match e with
  | Ast.TypeLit p -> 
    let l =
      match p with
      | PUni n -> n + 1
      | _ -> 0
    in
    ok (TypeLit p, VTypeLit (PUni l))
  | Ast.Hole ->
    let t = to_val ctx.env @@ gen_mv ctx.bds in
    let a = gen_mv ctx.bds in
    add_hole (loc, to_val ctx.env a);
    ok (a, t)
  | Ast.Const c ->
    let t =
      match c with
      | Int _ -> PInt
      | Float _ -> PFloat
      | String _ -> PString
      | Char _ -> PChar
      | Bool _ -> PBool
      | Unit -> PUnit
    in
    ok (Const c, VTypeLit t)
  | Ast.Tuple es ->
    let@ ets = List.map (infer ctx) es |> combine_errors in
    let es, ts = List.split ets in
    (Tuple es, VTuple ts)
  | Ast.If (c, t, f) ->
    let t = ((loc, PConst (Bool true)), None, t) in
    let f = ((loc, PConst (Bool false)), None, f) in
    let e = (loc, Ast.Match (c, [t; f])) in
    infer ctx e
  | Ast.Var i -> (
    let i = get_str i in
    match lookup_top i ctx with
    | Some (DCon b, t) -> ok (b, t)
    | Some (_, t) -> ok (Top i, t)
    | None -> (
      let r =
        Snoc.find_mapi
          (fun n (x, t) -> if x = i then Some (n, t) else None)
          ctx.tys
      in
      match r with
      | None ->
        make_err (Some loc, Printf.sprintf "Undefined identifier - '%s'." i)
      | Some (n, t) -> ok (Local (i, n), t)))
  | Ast.Lam (x, t) ->
    let x, t = replace_pattern x t in
    let a = to_val ctx.env @@ gen_mv ctx.bds in
    let@ t, b = infer (bind_var ~id:x ~t:a ctx) t in
    let b = (ctx.env, quote (ctx.lvl + 1) b) in
    (Lam (x, t), VPi (x, a, b))
  | Ast.Ap (b, l, r) ->
    (*TODO: recognise builtins. *)
    let* l, lt = infer ctx l in
    let* lt, ret =
      match force lt with
      | VPi (_, lt, ret) -> ok (lt, ret)
      | lt ->
        let lt' = to_val ctx.env (gen_mv ctx.bds) in
        let r' = (ctx.env, gen_mv (bind_var ~id:"x" ~t:lt ctx).bds) in
        let@ _ = unify loc ctx (VPi ("x", lt', r')) lt in
        (lt', r')
    in
    Log.dbg None (Format.asprintf "lt in pi := %a@." pp_val lt);
    let@ r = check ctx r lt in
    Log.dbg None
      (Format.asprintf "ap → %a@.ty → %a@." pp_tm (Ap (b, l, r)) pp_closure ret);
    (Ap (b, l, r), ret $$ to_val ctx.env r)
  | Ast.Pi ((i, _), l, r) ->
    let* l, n = is_type ctx l in
    let ctx = bind_var ~id:i ~t:(to_val ctx.env l) ctx in
    let* r, n' = is_type ctx l in
    let n = Int.max n n' in
    (Pi (i, l, r), VTypeLit (PUni n))
  | Ast.Let (p, t, b, n) -> (
    let i, b = replace_pattern p b in
    match t with
    | Some t ->
      let* t, _ = is_type ctx t in
      (* check that it's actually a type *)
      let vt = to_val ctx.env t in
      let* b = check ctx b vt in
      let@ n, ty = infer (define_var ~id:i ~v:(to_val ctx.env b) ~t:vt ctx) n in
      (Let (i, t, b, n), ty)
    | None ->
      let* b, t = infer ctx b in
      let@ n, ty = infer (define_var ~id:i ~v:(to_val ctx.env b) ~t ctx) n in
      let t = quote ctx.lvl t in
      (Let (i, t, b, n), ty))
  | Ast.Match (c, bs) ->
    (*TODO: check that the type of the pattern matches the type of the condition *)
    let* c, _ = infer ctx c in
    let check_branch (((_, _) as p), wb, ((loc, _) as b)) =
      let rec add_pat ctx (_, p) =
        match p with
        | PWild | PTypeLit _ | PConst _ -> ctx
        | PVar i -> 
          let t = to_val ctx.env @@ gen_mv ctx.bds in
          bind_var ~id:i ~t ctx
        | PTuple ps ->
          List.fold_left
            (fun ctx n -> let ctx = add_pat ctx n in { ctx with lvl = ctx.lvl + 1 })
            ctx
            ps
        | PCtor (_, args) ->
          let ctx =
            List.fold_left
              (fun ctx n -> let ctx = add_pat ctx n in { ctx with lvl = ctx.lvl + 1})
              ctx
              args
          in { ctx with lvl = ctx.lvl + List.length args }
      in
      let ctx = add_pat ctx p in
      Log.dbg None (Format.asprintf "env ⇒ [ %s ]@." (pp_sp pp_val ctx.env));
      let* wb =
        match wb with
        | Some wb -> check ctx wb (VTypeLit PBool)
        | None -> ok (Const (Bool true))
      in
      let@ b, t = infer ctx b in
      (loc, ((p, wb, b), t))
    in
    let@ bs, t =
      let* bs = List.map check_branch bs |> combine_errors in
      let ex = List.hd bs |> snd |> snd in
      let@ _ =
        List.filter_map
          (fun (_, (_, t)) ->
            (* if the inferred type is equal, then it's fine *)
            match unify loc ctx ex t with
            | Ok _ -> None
            | Error _ as e -> Some e)
          (List.tl bs)
        |> combine_errors
      in
      (List.map (fun v -> snd v |> fst) bs, ex)
    in
    (Match (c, bs), t)
  | Ast.RCons (cons, fs) -> (
    match List.find_opt (fun (_, c, _, _) -> cons = c) ctx.records with
    | None ->
      make_err
        (Some loc, Printf.sprintf "Undefined record constructor - '%s'." cons)
    | Some (_, cons, overall_t, ex_fs) ->
      (* recurses rightward into the type to get the return type *)
      let rec get_t = function
        | Ap (_, _, r) -> get_t r
        | v -> v
      in
      let g = List.length fs in
      let e = List.length ex_fs in
      if g <> e then
        make_err
          ( Some loc,
            Format.asprintf
              "In@[<v>correct amount of record fields.@,\
               Expected %d field(s).@,\
               Got %d field(s).@]"
              e g )
      else
        let* fs =
          (*
             we map over the expected fields, using them to pull the value from
             the given fields. this also ensures that the fields are in the
             correct order.
          *)
          List.map
            (fun (ex_i, ex_t) ->
              match List.assoc_opt ex_i fs with
              | None ->
                make_err
                  ( Some loc,
                    Printf.sprintf "Uninitialised record field - '%s'." ex_i )
              | Some got -> check ctx got ex_t)
            ex_fs
          |> combine_errors
        in
        let@ ret =
          let@ r, _ = is_type ctx overall_t in
          get_t r |> to_val ctx.env
        in
        let c =
          match lookup_top cons ctx with
          | None ->
            raise
              (Error.InternalError
                 "Internal error - record constructor not in ctx.")
          | _ -> Error.todo ""
        in
        (* cons { x₁ = y₁; ...; xₙ = yₙ }  ==> cons y₁ .. yₙ *)
        let cons = List.fold_left (fun n acc -> Ap (0, n, acc)) c fs in
        (cons, ret))
  | e -> Error.todo (Format.asprintf "finish infer - %a" Ast.pp_expr (loc, e))

and infer_universe loc = function
  | VTypeLit (PUni n) -> ok n
  | v -> make_err (Some loc, Format.asprintf "Expected a Type, but got %a." pp_val v)

(* check that the given expression is a type, and return the universe level alongside the term *)
and is_type (ctx : ctx) ((loc, _) as e : Ast.located_expr) : (tm * int) result =
  let* t, tty = infer ctx e in
  let@ n = infer_universe loc tty in
  t, n

let rec check_definition (ctx : ctx) (loc, (i, args, wb, b, locals)) :
    (located_definition list * ctx) result =
  (*
     we go through and typecheck each local definition. we first try to find any
     declared type signatures.
  *)
  let* locals, ctx' =
    match locals with
    | [] -> ok ([], ctx)
    | _ ->
      let* ctx =
        let@ ds =
          List.filter_map
            (function
              | _, Ast.Dec (i, sig_) -> Some (i, sig_)
              | _ -> None)
            locals
          |> List.map (fun (i, sig_) ->
              let@ sig_, _ = is_type ctx sig_ in
              (i, sig_))
          |> combine_errors
        in
        List.fold_left
          (fun ctx (i, sig_) -> bind_func ~id:i ~t:(to_val ctx.env sig_) ctx)
          ctx ds
      in
      let rec go ctx acc = function
        | [] -> (List.rev acc, ctx)
        | d :: ds -> (
          match check_definition ctx d with
          | Ok (d, ctx) -> go ctx (Ok d :: acc) ds
          | Error _ as e -> go ctx (e :: acc) ds)
      in
      let r, ctx =
        List.filter_map
          (function
            | loc, Ast.Def (i, args, wb, b, locals) ->
              Some (loc, (i, args, wb, b, locals))
            | _ -> None)
          locals
        |> go ctx []
      in
      let@ locals = combine_errors r in
      (List.flatten locals, ctx)
  in
  let* wb =
    match wb with
    | None -> ok (Const (Bool true))
    | Some wb -> check ctx' wb (VTypeLit PBool)
  in
  (*
     we replace any complex pattern (i.e. not just a variable) with a pattern
     identifier. we then construct a match expression with the actual patterns
  *)
  let* b, t =
    let b =
      match args with
      | [] -> b
      | [p] -> (loc, Ast.Lam (p, b))
      | ps -> List.fold_right (fun p acc -> (loc, Ast.Lam (p, acc))) ps b
    in
    Log.dbg None (Format.asprintf "body ⇒ %a@." Ast.pp_expr b);
    infer ctx' b
  in
  match lookup_top i ctx with
  | None ->
    let ctx = define_func ~id:i ~t ~v:b ctx in
    let t = quote 0 t in
    let d = (loc, (t, i, wb, b)) in
    ok (d :: locals, ctx)
  | Some (Axiom, t') ->
    Log.dbg None
      (Format.asprintf "un@[<v>ifying func types.@,Left: %a@,Right: %a@,@]"
         pp_val t' pp_val t);
    let@ _ = unify loc ctx t' t in
    let ctx = define_func ~id:i ~t ~v:b ctx in
    let t = quote 0 t' in
    let d = (loc, (t, i, wb, b)) in
    (d :: locals, ctx)
  | Some (Def _, _) ->
    make_err
      (Some loc, Printf.sprintf "The function '%s' has already been defined." i)
  | Some _ ->
    (* shouldn't occur unless it's an operator. *)
    make_err
      (Some loc, Printf.sprintf "The identifier '%s' is already in use." i)

let check_program ((n, mods, tdecls, defs) : Ast.program) : program result =
  let ctx = empty_ctx () in
  let* tdecls, ctx =
    let rec check_decls ctx acc ts =
      (* we check fields/variants in the form of string * located_expr. *)
      let pi_to_lam cons pi =
        (* 
            ( × ) : (a : Type) → (b: Type) → Pair a b
        *)
        let id_stack = 
          let rec go pi acc =
            match pi with
            | Pi (n, _, r) -> go r (acc @> n)
            | _ -> acc
          in
          go pi Snoc.empty
        in
        (* ( × ) a b ⇒ ( × ) 1 0 *)
        let ap =
          Snoc.fold_lefti
            (fun n acc i -> Ap (0, acc, Local (i, n)))
            (Top cons)
            id_stack
        in
        (* ( × ) 1 0 ⇒ λ λ. ( × ) 1 0 *)
        let v =
          Snoc.fold_right
            (fun i acc -> Lam (i, acc))
            id_stack
            ap
        in Log.dbg None (Format.asprintf "Turned pi into %a@." pp_tm v); v
      in
      let rec check_assoc ?(bind = false) ctx acc as_ =
        match as_ with
        | [] -> (ctx, List.rev acc)
        | (n, t) :: as_ -> (
          match is_type ctx t with
          | Error _ as e -> check_assoc ctx (e :: acc) as_
          | Ok (t, _) when bind ->
            let t' = to_val Snoc.empty t in
            let v = pi_to_lam n t in
            let ctx = define_dcon ~id:n ~t:t' ~v ctx in
            check_assoc ctx (Ok (n, t) :: acc) as_
          | Ok (t, _) -> check_assoc ctx (Ok (n, t) :: acc) as_)
      in
      match ts with
      | [] -> (ctx, List.rev acc)
      | (loc, (n, Ast.Alias t)) :: ts -> (
        match is_type ctx t with
        | Error _ as e -> check_decls ctx (e :: acc) ts
        | Ok (v, n) ->
          let a = (loc, (n, Alias v)) in
          check_decls
            (define_func ~id:n ~t:(VTypeLit (PUni n)) ~v ctx)
            (Ok a :: acc) ts)
      | (loc, (n, Ast.Variant (sig_, vs))) :: ts -> (
        let sig_ = is_type ctx sig_ in
        match sig_ with
        | Error _ as e -> check_decls ctx (e :: acc) ts
        | Ok (sig_, _) -> (
          let ctx = bind_func ~id:n ~t:(to_val Snoc.empty sig_) ctx in
          let ctx, vs = check_assoc ~bind:true ctx [] vs in
          match combine_errors vs with
          | Error _ as e -> check_decls ctx (e :: acc) ts
          | Ok vs ->
            let v = (loc, (n, Variant (sig_, vs))) in
            check_decls ctx (Ok v :: acc) ts))
      | (loc, (n, Ast.Record (cons, sig_'', fs))) :: ts -> (
        (* gather all record fields and make an ap *)
        let sig_ = is_type ctx sig_'' in
        match sig_ with
        | Error _ as e -> check_decls ctx (e :: acc) ts
        | Ok (sig_, _) -> (
          let ctx = define_tcon ~id:n ~t:(to_val Snoc.empty sig_) ctx in
          let ctx, fs = check_assoc ctx [] fs in
          match combine_errors fs with
          | Error _ as e -> check_decls ctx (e :: acc) ts
          | Ok fs ->
            let csig =
              List.fold_left
                (fun acc (_, n) -> Pi (fresh_bind_var (), n, acc))
                sig_ fs
            in
            Log.dbg None (Format.asprintf "csig := %a@." pp_tm csig);
            let ctx = bind_func ~id:cons ~t:(to_val Snoc.empty csig) ctx in
            let r = (loc, (n, Record (cons, sig_, fs))) in
            let ctx =
              (* we hold the record information for checking Ast.RCons and
                 Ast.RUpdate *)
              let fs = List.map (fun (i, t) -> (i, to_val Snoc.empty t)) fs in
              {ctx with records = (n, cons, sig_'', fs) :: ctx.records}
            in
            check_decls ctx (Ok r :: acc) ts))
    in
    let ctx, tdecls = check_decls ctx [] tdecls in
    let@ tdecls = combine_errors tdecls in
    (tdecls, ctx)
  in
  let* ctx =
    let rec go ctx = function
      | [] -> Ok ctx
      | (i, t) :: ts ->
        let* t, _ = is_type ctx t in
        let t' = to_val Snoc.empty t in
        Log.dbg None (Format.asprintf "bound %s to %a@." i pp_val t');
        go (bind_func ~id:i ~t:t' ctx) ts
    in
    let decs =
      List.filter_map
        (function
          | _, Ast.Dec (i, t) -> Some (i, t)
          | _ -> None)
        defs
    in
    go ctx decs
  in
  let* defs =
    let defs =
      List.filter_map
        (function
          | loc, Ast.Def (i, as_, wb, b, wb') -> Some (loc, (i, as_, wb, b, wb'))
          | _ -> None)
        defs
    in
    let rec go ctx acc = function
      | [] -> acc
      | d :: ds -> (
        match check_definition ctx d with
        | Error _ as e -> go ctx (e :: acc) ds
        | Ok (d, ctx) -> go ctx (Ok d :: acc) ds)
    in
    go ctx [] defs |> combine_errors
  in
  match !holes with
  | [] -> ok (n, mods, tdecls, List.rev defs |> List.flatten)
  | _ -> make_err (None, fmt_holes ())

(* pretty printing *)
let rec pp_ty_decl out ((_, (i, t)) : located_ty_decl) =
  match t with
  | Alias _ -> Format.fprintf out "(ty@[<v>pe %s %a@])" i pp_tdecl_type t
  | _ -> Format.fprintf out "(ty@[<v>pe %s@,%a@])" i pp_tdecl_type t

and pp_tdecl_type out (t : tdecl_type) =
  let pp_field out (i, t) = Format.fprintf out "(%s %a)" i pp_tm t in
  match t with
  | Alias t -> pp_tm out t
  | Record (cons, tsig, r) ->
    Format.fprintf out "(re@[<v>cord %s { %a }@,%a@])" cons pp_tm tsig
      Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out "@,") pp_field)
      r
  | Variant (tsig, v) ->
    Format.fprintf out "(va@[<v>riant { %a }@,%a@])" pp_tm tsig
      Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out "@,") pp_field)
      v

let pp_when_block out (when_block : tm) =
  Format.fprintf out "(when @[<hov>%a@])" pp_tm when_block

let pp_definition out ((_, (t, f, when_block, body)) : located_definition) =
  Format.fprintf out "de@[<v>f %s { %a }@,%a@,%a@]@.@." f pp_tm t pp_when_block
    when_block pp_tm body

let pp_module out (mod_name : string) =
  Format.fprintf out "(module %s)" mod_name

let pp_program out ((prog_name, imports, types, body) : program) =
  Format.fprintf out "%a@.@.%a@.@.%a@.@.%a@." pp_module prog_name
    Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out "@.") pp_import)
    imports
    Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out "@.") pp_ty_decl)
    types
    Format.(
      pp_print_list ~pp_sep:(fun out () -> fprintf out "@.") pp_definition)
    body
