(* debugging *)
let border () =
  Seq.init 30 (fun _ -> '-') |> String.of_seq |> print_endline;
  print_newline ()

let flip = Fun.flip

let fresh_i =
  let i = ref (-1) in
  fun () ->
    incr i;
    !i


(* de bruijn indices and levels *)
type ix = int
type lvl = int
type mv = int

module M = Map.Make (Int)

(* bound or defined variables *)
type bd = B | D

(*NOTE: removed location tracking, might be useful to keep it *)
(* core syntax, tms *)
type tm =
  | Local of ix (* local variable as de bruijn index *)
  | Ap of binder * tm * tm
  | Mv of mv
  | IMv of mv * bd list (* generated mv *)
  | Tuple of tm list
  | Let of string * tm * tm * tm (* let p₁ ... pₙ : type = e₁ in e₂ *)
  | Match of tm * (located_pattern * tm * tm) list
    (* match cond to 
       | p₁ when x₁ => y₁
       ...
       | pₙ when xₙ => yₙ*)
  | Lam of string * tm
  | Const of const
  | TypeLit of prim
  | Pi of tm * tm

(* values for NbE *)
and val_ =
  | VLam of string * closure
  | VRigid of lvl * spine
  | VFlex of mv * spine
  | VTuple of val_ list
  | VMatch of val_ * (located_pattern * val_ * val_) list
  | VPi of val_ * closure
  | VTypeLit of prim
  | VConst of const

and env = val_ list

(* list of variables that a mv or local is applied to *)
and spine = val_ list

(* metavariable entry in the mctx *)
and mv_entry = Solved of val_ | Unsolved
and closure = env * tm (* local variables in lambdas *)

(* top level extras *)
type located_ty_decl = Location.t * ty_decl
and ty_decl = string * tdecl_type

and tdecl_type =
  | Alias of tm
  | Variant of tm * (string * tm) list
  | Record of string * tm * (string * tm) list

type located_definition = Location.t * definition
and definition = tm * string * tm * tm
(* type, identifer, optional when-block, body, optional with-block *)

type program = string * located_import list * located_ty_decl list * located_definition list

let mctx : mv_entry M.t ref = ref M.empty

(* shouldn't fail, all mvs are either generated by the compiler or by the user through holes and would be tracked *)
let lookup_mv (m : mv) : mv_entry = M.find m !mctx 

(* generate an unsolved meta variable *)
let gen_mv bds : tm =
  let mv = fresh_i () in
  mctx := M.add mv Unsolved !mctx;
  IMv (mv, bds)


(* early declaration of val/tm for errors *)
let rec pp_tm out (tm : tm) =
  match tm with
  | Local i -> Format.fprintf out "%d" i
  | Const c -> pp_const out c
  | TypeLit p -> pp_prim out p
  | Ap (_, f, arg) -> Format.fprintf out "(@[<hov>%a@ %@ %a@])" pp_tm f pp_tm arg
  | Tuple t ->
      Format.fprintf out "(@[<hov>%a@])"
        Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out ",@ ") pp_tm)
        t
  | Let (p, ty, v, n) ->
    Format.fprintf out "@[<v 2>let %s : %a =@,%a@]@,in@,%a" p pp_tm ty pp_tm v pp_tm n
  | Lam (arg, body) -> Format.fprintf out "λ@[<v> %s. {@,%a@]@,}" arg pp_tm body
  | Match (c, bs) ->
      let pp_branch out (p, wb, b) =
        Format.fprintf out "(wh@[<v>en %a)@,(%a) ⇒ %a@]" pp_tm wb pp_pattern p pp_tm b
      in
      Format.fprintf out "ma@[<v>tch (%a)@,%a@]" pp_tm c
        Format.(pp_print_list ~pp_sep:pp_print_cut pp_branch)
        bs
  | Pi (l, r) -> Format.fprintf out "%a → %a" pp_tm l pp_tm r
  | Mv m -> Format.fprintf out "?meta%d" m
  | IMv (m, bds) ->
      let to_str bd = match bd with B -> "b" | D -> "d" in
      Format.fprintf out "?meta%d (%s)" m (List.map to_str bds |> String.concat " ")


let rec pp_val out (v : val_) =
  match v with
  | VLam (p, cl) -> Format.fprintf out "λ@[<v>@ %s.@,%a@]" p pp_closure cl
  | VTuple vs ->
      Format.fprintf out "(%a)"
        Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out ",@ ") pp_val)
        vs
  | VMatch (c, bs) ->
      let pp_branch out (p, wb, b) =
        Format.fprintf out "(wh@[<v>en %a)@,(%a)@ ⇒@ %a@]" pp_val wb pp_pattern p pp_val b
      in
      Format.fprintf out "ma@[<v>tch (%a)@,%a@]" pp_val c
        Format.(pp_print_list ~pp_sep:pp_print_cut pp_branch)
        bs
  | VPi (l, cl) -> Format.fprintf out "%a → %a" pp_val l pp_closure cl
  | VTypeLit p -> pp_prim out p
  | VConst c -> pp_const out c
  | VRigid (lvl, sp) ->
      Format.fprintf out "rigid%d (%a)" lvl
        Format.(pp_print_list ~pp_sep:pp_print_space pp_val)
        sp
  | VFlex (m, sp) ->
      Format.fprintf out "?meta%d (%a)" m Format.(pp_print_list ~pp_sep:pp_print_space pp_val) sp


and pp_closure out ((_, tm) : closure) = pp_tm out tm

(* term → val *)
let rec to_val (env : env) (tm : tm) : val_ =
  match tm with
  | Local i -> 
    Log.dbg None (Printf.sprintf "Indexed with local idx %d, env size %d." (i + 1) (List.length env));
    List.nth env i (*NOTE: shouldn't fail unless code is buggy *)
  | TypeLit p -> VTypeLit p
  | Const c -> VConst c
  | Tuple ts -> VTuple (List.map (to_val env) ts)
  | Lam (p, t) -> VLam (p, (env, t))
  | Pi (l, r) -> VPi (to_val env l, (env, r))
  | Ap (_, l, r) -> v_ap (to_val env l) (to_val env r)
  | Mv m -> v_meta m
  | IMv (m, bds) -> v_ap_bds env bds (v_meta m)
  | Match (c, bs) ->
      let c = to_val env c in
      let bs = List.map (fun (p, wb, b) -> (p, to_val env wb, to_val env b)) bs in
      VMatch (c, bs)
  | Let (_, _, v, n) ->
      let inner = to_val env v in
      to_val (inner :: env) n


(* 
   applies a closure to a value and evaluates it 
   pretty much β-reduction.
*)
and ( $$ ) ((env, t) : closure) (v : val_) : val_ = to_val (v :: env) t

and v_ap l r =
  match l with
  | VLam (_, t) -> t $$ r
  | VFlex (m, spine) -> VFlex (m, r :: spine)
  | VRigid (lvl, spine) -> VRigid (lvl, r :: spine)
  | _ -> raise (Error.InternalError "Internal Error - called `v_ap` on non-function.")


(* unroll a spine *)
and v_ap_sp spine v = match spine with [] -> v | s :: spvs -> v_ap (v_ap_sp spvs v) s
and v_meta m = match M.find m !mctx with Solved v -> v | Unsolved -> VFlex (m, [])

and v_ap_bds env bds m =
  match (env, bds) with
  | [], [] -> m
  | e :: env, bd :: bds -> (
      match bd with B -> v_ap (v_ap_bds env bds m) e | D -> v_ap_bds env bds m)
  | _ -> raise (Error.InternalError "Internal Error - mismatched env/bds list.")


(* reduce a metavariable if possible *)
let force = function
  | VFlex (m, sp) as flex -> ( match lookup_mv m with Solved v -> v_ap_sp sp v | Unsolved -> flex)
  | v -> v


(* db level → db index *)
let to_ix (l : lvl) (r : lvl) = l - r - 1

(* val → tm *)
let rec quote (lvl : lvl) (v : val_) : tm =
  match force v with
  | VTypeLit t -> TypeLit t
  | VConst c -> Const c
  | VTuple vs -> Tuple (List.map (quote lvl) vs)
  | VMatch (c, bs) ->
      let c = quote lvl c in
      let bs = List.map (fun (p, wb, b) -> (p, quote lvl wb, quote lvl b)) bs in
      Match (c, bs)
  | VLam (p, cl) ->
      (* 
         increment the level as we move into the closure
         add a local with the current level to capture the current argument
      *)
      Lam (p, quote (lvl + 1) (cl $$ VRigid (lvl, [])))
  | VPi (l, cl) ->
      let l = quote lvl l in
      let r = quote (lvl + 1) (cl $$ VRigid (lvl, [])) in
      Pi (l, r)
  | VFlex (m, sp) -> quote_sp lvl (Mv m) sp
  | VRigid (l, sp) -> quote_sp lvl (Local (to_ix lvl l)) sp


(* unroll a flex/rigid into a set of applications *)
and quote_sp (lvl : lvl) (v : tm) (sp : spine) : tm =
  match sp with [] -> v | s :: sp -> Ap (0, quote_sp lvl v sp, quote lvl s)


(* type checking *)
type 'a result = 'a Base.Or_error.t

let ( let* ) = Base.Or_error.( >>= )
let ( let@ ) = Base.Or_error.( >>| )
let ok (v : 'a) : 'a result = Ok v
let make_err (e : Error.t) : 'a result = Base.Or_error.error_string @@ Error.format_err e
let ( <|> ) l r ctx = match l ctx with Ok _ as v -> v | Error _ -> r ctx
let combine_errors = Base.Or_error.combine_errors
let combine_errors_unit = Base.Or_error.combine_errors_unit

(* 
   partial renaming.
   the solution to a problem like ?α spine =? t is ?α = λ x₁ ... xₙ . t, where the solution has a context Δ and the spine has a context Γ.
   we need to rename spine locals so that they're valid within the Δ context, which is where partial renaming comes in.
*)
type partial = { gamma : lvl; delta : lvl; subs : lvl M.t }

let extend_pn (p : partial) : partial =
  { gamma = p.gamma + 1; delta = p.delta + 1; subs = M.add p.gamma p.delta p.subs }


(* computes Γ ↦ Δ *)
let invert_mapping (loc: Location.t) (delta : lvl) (sp : spine) : partial result =
  let rec go = function
    | [] -> ok @@ (0, M.empty)
    | s :: sp -> (
        let* gamma, subs = go sp in
        match force s with
        | VRigid (l, []) -> (
            match M.mem l subs with
            | true -> make_err (Some loc, "Non-linear bound variable in unification problem.")
            | false -> ok @@ (gamma + 1, M.add l gamma subs))
        | _ -> make_err (Some loc, "Unbound value in unification problem."))
  in
  let@ gamma, subs = go sp in
  { gamma; delta; subs }


let rename (loc: Location.t) (mv : mv) (p : partial) (v : val_) : tm result =
  let rec go_sp p sp v : tm result =
    match sp with
    | [] -> ok v
    | s :: sp ->
        let* r = go p s in
        let@ l = go_sp p sp v in
        Ap (0, l, r)
  and go p v : tm result =
    let v' = v in
    let v = force v in
    Format.fprintf Format.std_formatter "before renaming, forced [ %a ⇒ %a ]@." pp_val v' pp_val v;
    match force v with
    | VFlex (mv', sp) as flex ->
        Format.fprintf Format.std_formatter "with %a, compared %d to %d@.@." pp_val flex mv mv';
        if mv = mv' then make_err (Some loc, "Found infinite type in unification problem.")
        else go_sp p sp (Mv mv')
    | VRigid (l, sp) -> (
        match M.find_opt l p.subs with
        | None -> make_err (Some loc, "Type variable escapes scope.")
        | Some l ->
            let l = to_ix p.gamma l in
            go_sp p sp (Local (to_ix p.gamma l)))
    | VLam (a, cl) ->
        let@ b = go (extend_pn p) (cl $$ VRigid (p.delta, [])) in
        Lam (a, b)
    | VPi (l, cl) ->
        let* l = go p l in
        let@ r = go (extend_pn p) (cl $$ VRigid (p.delta, [])) in
        Pi (l, r)
    | VMatch (c, bs) ->
        let* c = go p c in
        let@ bs =
          List.map
            (fun (pat, wb, b) ->
              let* wb = go p wb in
              let@ b = go p b in
              (pat, wb, b))
            bs
          |> combine_errors
        in
        Match (c, bs)
    | VTuple vs ->
        let@ vs = List.map (go p) vs |> combine_errors in
        Tuple vs
    | VConst c -> ok @@ Const c
    | VTypeLit p -> ok @@ TypeLit p
  in
  go p v


let solve (loc: Location.t) (gamma : lvl) (mv : mv) (sp : spine) (rhs : val_) : unit result =
  let nest lvl v =
    let rec go n t acc = if n = acc then t else Lam ("x" ^ string_of_int acc, go n t (acc + 1)) in
    go lvl v 0
  in
  let* p = invert_mapping loc gamma sp in
  Log.dbg None (Format.asprintf "Solving rhs ⇒ %a@." pp_val rhs);
  let@ rhs = rename loc mv p rhs in
  let sol = to_val [] @@ nest p.gamma rhs in
  mctx := M.add mv (Solved sol) !mctx


let uni_err loc pp_func ex got =
  make_err
    (loc, Format.asprintf "Fa@[<v>iled to unify:@,Left: %a@,Right: %a@,@]" pp_func ex pp_func got)


let rec unify (loc : Location.t) (lvl : lvl) (l : val_) (r : val_) : unit result =
  let rec unify_sp sp sp' =
    match (sp, sp') with
    | [], [] -> ok ()
    | s :: sp, s' :: sp' ->
        let* _ = unify loc lvl s s' in
        unify_sp sp sp'
    | _ -> make_err (Some loc, "Rigid mismatch in unification.")
  in
  match (force l, force r) with
  | VTypeLit l, VTypeLit r -> if l#=r then ok () else uni_err (Some loc) pp_prim l r
  | VConst l, VConst r -> if l %= r then ok () else uni_err (Some loc) pp_const l r
  | VPi (ll, lc), VPi (rl, rc) ->
      (* go into the closure and check that the bound variables are equal *)
      let* _ = unify loc lvl ll rl in
      unify loc (lvl + 1) (lc $$ VRigid (lvl, [])) (rc $$ VRigid (lvl, []))
  | VLam (_, lc), VLam (_, rc) ->
      unify loc (lvl + 1) (lc $$ VRigid (lvl, [])) (rc $$ VRigid (lvl, []))
  | VLam (_, cl), t | t, VLam (_, cl) ->
      (*
       check that applying the right to the captured variable is 
       the same as going into the closure with the captured variable
       (fun x -> M x) N => M N
      *)
      unify loc (lvl + 1) (cl $$ VRigid (lvl, [])) (v_ap t (VRigid (lvl, [])))
  | VMatch (c, bs), VMatch (c', bs') when List.length bs = List.length bs' ->
      let unify_branch (_, wb, b) (_, wb', b') =
        let* _ = unify loc lvl wb wb' in
        (*NOTE: maybe don't unify it? *)
        unify loc lvl b b'
      in
      let* _ = unify loc lvl c c' in
      List.map2 unify_branch bs bs' |> combine_errors_unit
  | VRigid (mv, sp), VRigid (mv', sp') when List.length sp = List.length sp' && mv = mv' ->
      unify_sp sp sp'
  | VFlex (mv, sp), VRigid (mv', sp') when List.length sp = List.length sp' && mv = mv' ->
      unify_sp sp sp'
  | (VFlex (mv, sp) as flex), t ->
      Format.fprintf Format.std_formatter
        "!at@[<v>tempting to solve the unification of@,left: [ %a ]@,right: [ %a ]@]@.@." pp_val
        flex pp_val t;
      solve loc lvl mv sp t
  | t, (VFlex (mv, sp) as flex) ->
      Format.fprintf Format.std_formatter
        "at@[<v>tempting to solve the unification of@,left: [ %a ]@,right: [ %a ]@]@.@." pp_val t
        pp_val flex;
      solve loc lvl mv sp l
  | _ -> uni_err (Some loc) pp_val l r


(* record name, constructor, overall type, field name & type *)
type record_info = string * string * Ast.located_expr * (string * val_) list
type ty = string * val_
type ctx = { env : env; funcs: (string * (tm * val_)) list; tys : ty list; records : record_info list; lvl : lvl; bds : bd list }

let empty_ctx () = { env = []; funcs = []; tys = []; records = []; lvl = 0; bds = [] }

(* 
   doesn't affect the env or bds to prevent extra bds from being added where they shouldn't be
*)
let bind_func ~(id : string) ~(t : val_) (ctx : ctx) =
  { ctx with tys = (id, t) :: ctx.tys; lvl = ctx.lvl + 1 }


let bind_var ~(id : string) ~(t : val_) (ctx : ctx) =
  {
    ctx with
    env = VRigid (ctx.lvl, []) :: ctx.env;
    tys = (id, t) :: ctx.tys;
    lvl = ctx.lvl + 1;
    bds = B :: ctx.bds;
  }


let define_var ~(id : string) ~(v : val_) ~(t : val_) (ctx : ctx) =
  { ctx with env = v :: ctx.env; tys = (id, t) :: ctx.tys; lvl = ctx.lvl + 1; bds = D :: ctx.bds }

let define_func ~(id : string) ~(v : tm) ~(t : val_) (ctx : ctx) =
  { ctx with funcs = (id, (v, t)) :: ctx.funcs }


let dump_bds ctx = { ctx with bds = [] }
let fresh_pattern_var () : string = "__p_" ^ (fresh_i () |> string_of_int)

let replace_pattern ((_, p) as p' : located_pattern) ((loc, _) as b : Ast.located_expr) :
    string * Ast.located_expr =
  match p with
  | PVar i -> (i, b)
  | _ ->
      (* we create a match expr to remove the pattern from the expression *)
      let i = fresh_pattern_var () in
      Format.fprintf Format.std_formatter "pattern generated for [ %a ⇒ %s ]@." pp_pattern p' i;
      let match_ =
        let c = (loc, Ast.Var (Ident i)) in
        let branch = [ ((loc, p), None, b) ] in
        (loc, Ast.Match (c, branch))
      in
      (i, match_)


let rec check (ctx : ctx) ((loc, e) : Ast.located_expr) (ex : val_) : tm result =
  match (e, force ex) with
  | Ast.Lam (p, b), VPi (l, cl) ->
      let i, b = replace_pattern p b in
      Printf.printf "called bind_var on argument %s\n" i;
      let@ b = check (bind_var ~id:i ~t:l ctx) b (cl $$ VRigid (ctx.lvl, [])) in
      Lam (i, b)
  | Ast.Let (p, t, b, n), t' -> (
      let i, b = replace_pattern p b in
      match t with
      | Some t ->
          let* t = is_type ctx t in
          let vt = to_val ctx.env t in
          let* b = check ctx b vt in
          let@ n = check (define_var ~id:i ~v:(to_val ctx.env b) ~t:vt ctx) n t' in
          Let (i, t, b, n)
      | None ->
          let* b, t = infer ctx b in
          let@ n = check (define_var ~id:i ~v:(to_val ctx.env b) ~t ctx) n t' in
          let t = quote ctx.lvl t in
          Let (i, t, b, n))
  | Ast.Hole, _ -> ok @@ gen_mv ctx.bds
  | e, ex ->
      let* e, t = infer ctx (loc, e) in
      let@ _ = unify loc ctx.lvl t ex in
      e


and infer (ctx : ctx) ((loc, e) : Ast.located_expr) : (tm * val_) result =
  match e with
  | Ast.TypeLit p -> ok @@ (TypeLit p, VTypeLit PUni)
  | Ast.Hole ->
      let t = to_val ctx.env @@ gen_mv ctx.bds in
      let a = gen_mv ctx.bds in
      Format.fprintf Format.std_formatter
        "generated hole type: %a@.generated hole expression: %a@.@." pp_val t pp_tm a;
      ok (a, t)
  | Ast.Const c ->
      let t =
        match c with
        | Int _ -> PInt
        | Float _ -> PFloat
        | String _ -> PString
        | Char _ -> PChar
        | Bool _ -> PBool
        | Unit -> PUnit
      in
      ok @@ (Const c, VTypeLit t)
  | Ast.Tuple es ->
      let@ ets = List.map (infer ctx) es |> combine_errors in
      let es, ts = List.split ets in
      (Tuple es, VTuple ts)
  | Ast.If (c, t, f) ->
      let t = ((loc, PConst (Bool true)), None, t) in
      let f = ((loc, PConst (Bool false)), None, f) in
      let e = (loc, Ast.Match (c, [ t; f ])) in
      infer ctx e
  | Ast.Var i -> (
      let i = get_str i in
      (match List.assoc_opt i ctx.funcs with
      | Some (b, t) -> ok (b, t)
      | None -> 
        let r = List.find_mapi (fun n (x, t) -> if x = i then Some (n, t) else None) ctx.tys in
        (match r with
        | None -> make_err (Some loc, Printf.sprintf "Undefined identifier - '%s'." i)
        | Some (n, t) -> 
          Printf.printf "local creation: %s → %d\n" i n;
          ok (Local n, t))))
  | Ast.Lam (x, t) -> (
      match x with
      (* | _, PWild -> *)
      (* Format.fprintf Format.std_formatter "wild ignorace: %a@." Ast.pp_expr b; *)
      (*   let t' = gen_mv ctx.bds in *)
      (*   let t = to_val ctx.env t' in *)
      (*   let@ b, l = infer ctx b in *)
      (*   let r = (ctx.env, quote (ctx.lvl + 1) t) in *)
      (*   (Lam (Default, b), VPi (l, r)) *)
      | _ ->
          let x, t = replace_pattern x t in
          let a' = gen_mv ctx.bds in
          let a = to_val ctx.env a' in
          (* Format.fprintf Format.std_formatter "%s ⇒ t': %a@." p pp_tm t'; *)
          (* Format.fprintf Format.std_formatter "%s ⇒ t: %a@." p pp_val t; *)
          (* Printf.printf "called bind_var on argument %s\n" p; *)
          let ctx = bind_var ~id:x ~t:a ctx in
          print_newline ();
          let@ t, b = infer ctx t in
          Format.fprintf Format.std_formatter "generated type of left: %a@." pp_val a;
          Format.fprintf Format.std_formatter "inferred type of right: %a@." pp_val b;
          let b = (ctx.env, quote (ctx.lvl + 1) b) in
          Format.fprintf Format.std_formatter "quoted type of right: %a@.@." pp_closure b;
          Format.fprintf Format.std_formatter "overall type: %a@.@." pp_val (VPi (a, b));
          (Lam (x, t), VPi (a, b)))
  | Ast.Ap (b, l, r) ->
      (*TODO: recognise builtins. *)
      let* l, l' = infer ctx l in
      let* l', ret =
        match force l' with
        | VPi (l', ret) -> ok (l', ret)
        | l' ->
            let l'' = to_val ctx.env (gen_mv ctx.bds) in
            let r' = (ctx.env, gen_mv (bind_var ~id:"x" ~t:l' ctx).bds) in
            let@ _ = unify loc ctx.lvl (VPi (l'', r')) l' in
            (l'', r')
      in
      let@ r = check ctx r l' in
      (Ap (b, l, r), ret $$ to_val ctx.env r)
  | Ast.Pi (bind, l, r) -> (
      let* l = is_type ctx l in
      match bind with
      | None ->
          let* r = is_type ctx r in
          ok @@ (Pi (l, r), VTypeLit PUni)
      | Some (i, _) ->
          (* ignoring the type of bind for now. *)
          let l' = to_val ctx.env l in
          let* r = is_type (bind_var ~id:i ~t:l' ctx) r in
          ok @@ (Pi (l, r), VTypeLit PUni))
  | Ast.Let (p, t, b, n) -> (
      let i, b = replace_pattern p b in
      match t with
      | Some t ->
          let* t = is_type ctx t in
          (* check that it's actually a type *)
          let vt = to_val ctx.env t in
          let* b = check ctx b vt in
          let@ n, ty = infer (define_var ~id:i ~v:(to_val ctx.env b) ~t:vt ctx) n in
          (Let (i, t, b, n), ty)
      | None ->
          let* b, t = infer ctx b in
          let@ n, ty = infer (define_var ~id:i ~v:(to_val ctx.env b) ~t ctx) n in
          let t = quote ctx.lvl t in
          (Let (i, t, b, n), ty))
  | Ast.Match (c, bs) ->
      (*TODO: check that the type of the pattern matches the type of the condition *)
      let* c, _ = infer ctx c in
      let check_branch (p, wb, ((loc, _) as b)) =
        let* wb =
          match wb with Some wb -> check ctx wb (VTypeLit PBool) | None -> ok (Const (Bool true))
        in
        let@ b, t = infer ctx b in
        (loc, ((p, wb, b), t))
      in
      let@ bs, t =
        let* bs = List.map check_branch bs |> combine_errors in
        let ex = List.hd bs |> snd |> snd in
        let@ _ =
          List.filter_map
            (fun (_, (_, t)) ->
              (* if the inferred type is equal, then it's fine *)
              match unify loc ctx.lvl ex t with
              | Ok _ -> None
              | Error _ as e -> Some e)
            bs
          |> combine_errors
        in
        (List.map (fun v -> snd v |> fst) bs, ex)
      in
      (Match (c, bs), t)
  | Ast.RCons (cons, fs) -> (
      match List.find_opt (fun (_, c, _, _) -> cons = c) ctx.records with
      | None -> make_err (Some loc, Printf.sprintf "Undefined record constructor - '%s'." cons)
      | Some (_, cons, overall_t, ex_fs) ->
          (* recurses rightward into the type to get the return type *)
          let rec get_t = function Ap (_, _, r) -> get_t r | v -> v in
          let g = List.length fs in
          let e = List.length ex_fs in
          if g <> e then
            make_err
              ( Some loc,
                Format.asprintf
                  "In@[<v>correct amount of record fields.@,\
                   Expected %d field(s).@,\
                   Got %d field(s).@]"
                  e g )
          else
            let* fs =
              (*
                we map over the expected fields, using them to pull the value from the given fields.
                this also ensures that the fields are in the correct order.
              *)
              List.map
                (fun (ex_i, ex_t) ->
                  match List.assoc_opt ex_i fs with
                  | None ->
                      make_err (Some loc, Printf.sprintf "Uninitialised record field - '%s'." ex_i)
                  | Some got ->
                      Format.fprintf Format.std_formatter "%s: %a@.@." ex_i pp_val ex_t;
                      check ctx got ex_t)
                ex_fs
              |> combine_errors
            in
            let@ ret =
              let@ r = is_type ctx overall_t in
              get_t r |> to_val ctx.env
            in
            let c =
              let r =
                List.find_mapi (fun n (x, t) -> if x = cons then Some (n, t) else None) ctx.tys
              in
              match r with
              | None ->
                  raise (Error.InternalError "Internal error - record constructor not in ctx.")
              | Some (n, _) -> Local n
            in
            (* cons { x₁ = y₁; ...; xₙ = yₙ }  ==> cons y₁ .. yₙ *)
            let cons = List.fold_left (fun n acc -> Ap (0, n, acc)) c fs in
            (cons, ret))
  | e -> Error.todo (Format.asprintf "finish infer - %a" Ast.pp_expr (Location.dummy_loc, e))


and is_type (ctx : ctx) (e : Ast.located_expr) : tm result =
  (* check if it's a type of a type, or a builtin type *)
  ( ( ( ( ( ((fun ctx -> check ctx e (VTypeLit PUni)) <|> fun ctx -> check ctx e (VTypeLit PInt))
          <|> fun ctx -> check ctx e (VTypeLit PFloat) )
        <|> fun ctx -> check ctx e (VTypeLit PString) )
      <|> fun ctx -> check ctx e (VTypeLit PChar) )
    <|> fun ctx -> check ctx e (VTypeLit PBool) )
  <|> fun ctx -> check ctx e (VTypeLit PUnit) )
    ctx


let rec check_definition (ctx : ctx) (loc, (i, args, wb, b, locals)) :
    (located_definition list * ctx) result =
  (*
    we go through and typecheck each local definition.
    we first try to find any declared type signatures.
  *)
  Log.dbg None (Printf.sprintf "checking function %s" i);
  let* locals, ctx =
    match locals with
    | [] -> ok ([], ctx)
    | _ ->
        let* ctx =
          let@ ds =
            List.filter_map (function _, Ast.Dec (i, sig_) -> Some (i, sig_) | _ -> None) locals
            |> List.map (fun (i, sig_) ->
                let@ sig_ = is_type ctx sig_ in
                (i, sig_))
            |> combine_errors
          in
          List.fold_left (fun ctx (i, sig_) -> bind_func ~id:i ~t:(to_val ctx.env sig_) ctx) ctx ds
        in
        let rec go ctx acc = function
          | [] -> (List.rev acc, ctx)
          | d :: ds -> (
              match check_definition ctx d with
              | Ok (d, ctx) -> go ctx (Ok d :: acc) ds
              | Error _ as e -> go ctx (e :: acc) ds)
        in
        let r, ctx =
          List.filter_map
            (function
              | loc, Ast.Def (i, args, wb, b, locals) -> Some (loc, (i, args, wb, b, locals))
              | _ -> None)
            locals
          |> go ctx []
        in
        let@ locals = combine_errors r in
        (List.flatten locals, ctx)
  in
  let* wb =
    match wb with None -> ok (Const (Bool true)) | Some wb -> check ctx wb (VTypeLit PBool)
  in
  (*
    we replace any complex pattern (i.e. not just a variable) with a pattern identifier.
    we then construct a match expression with the actual patterns
  *)
  let* b, t =
    match args with
    | [] -> 
      Format.fprintf Format.std_formatter "naturally lambda:@.%a@.@." Ast.pp_expr b;
      infer ctx b
    | [ p ] ->
        let b = (loc, Ast.Lam (p, b)) in
        infer ctx b
    | ps ->
        (* let match_ = *)
        (*   let c = *)
        (*     let is = *)
        (*       List.map *)
        (*         (fun (loc, p) -> *)
        (*           match p with *)
        (*           | PVar i -> (loc, Ast.Var (Ident i)) *)
        (*           | _ -> (loc, Ast.Var (Ident (fresh_pattern_var ())))) *)
        (*         ps *)
        (*     in *)
        (*     (loc, Ast.Tuple is) *)
        (*   in *)
        (*   let bs = [ ((loc, PTuple ps), None, b) ] in *)
        (*   (loc, Ast.Match (c, bs)) *)
        (* in *)
        let b = List.fold_right (fun p acc -> (loc, Ast.Lam (p, acc))) ps b in
        Format.fprintf Format.std_formatter "manufactured lambda:@.%a@.@." Ast.pp_expr b;
        infer ctx b
  in
  let@ res =
    match List.assoc_opt i ctx.tys with
    | None ->
        let ctx = define_func ~id:i ~t ~v:b ctx in
        let t = quote ctx.lvl t in
        let d = (loc, (t, i, wb, b)) in
        ok @@ (d :: locals, ctx)
    | Some t' ->
        let@ _ = unify loc ctx.lvl t' t in
        let ctx = define_func ~id:i ~t ~v:b ctx in
        let t = quote ctx.lvl t' in
        let d = (loc, (t, i, wb, b)) in
        (d :: locals, ctx)
    in Log.dbg None (Printf.sprintf "finished function %s" i); res


let check_program ((n, mods, tdecls, defs) : Ast.program) : program result =
  let ctx = empty_ctx () in
  let* tdecls, ctx =
    let rec check_decls ctx acc ts =
      (* we check fields/variants in the form of string * located_expr. *)
      let rec check_assoc ?(bind = false) ctx acc as_ =
        match as_ with
        | [] -> (ctx, List.rev acc)
        | (n, t) :: as_ -> (
            match is_type ctx t with
            | Error _ as e -> check_assoc ctx (e :: acc) as_
            | Ok t when bind ->
                let t' = to_val ctx.env t in
                let ctx = bind_func ~id:n ~t:t' ctx in
                check_assoc ctx (Ok (n, t) :: acc) as_
            | Ok t -> check_assoc ctx (Ok (n, t) :: acc) as_)
      in
      match ts with
      | [] -> (ctx, List.rev acc)
      | (loc, (n, Ast.Alias t)) :: ts -> (
          match is_type ctx t with
          | Error _ as e -> check_decls ctx (e :: acc) ts
          | Ok t ->
              let a = (loc, (n, Alias t)) in
              let t = to_val ctx.env t in
              check_decls (bind_func ~id:n ~t ctx) (Ok a :: acc) ts)
      | (loc, (n, Ast.Variant (sig_, vs))) :: ts -> (
          let sig_ = is_type ctx sig_ in
          (* we bind variants so that they become 'functions' *)
          match sig_ with
          | Error _ as e -> check_decls ctx (e :: acc) ts
          | Ok sig_ -> (
              let sig_' = to_val ctx.env sig_ in
              (* 
               we bind before checking variants to allow reference to the union type in variants 
               i.e. | ( :: ) : (a : Type) -> List a -> List a
              *)
              let ctx = bind_func ~id:n ~t:sig_' ctx in
              let ctx, vs = check_assoc ~bind:true ctx [] vs in
              match combine_errors vs with
              | Error _ as e -> check_decls ctx (e :: acc) ts
              | Ok vs ->
                  let v = (loc, (n, Variant (sig_, vs))) in
                  check_decls ctx (Ok v :: acc) ts))
      | (loc, (n, Ast.Record (cons, sig_'', fs))) :: ts -> (
          (* gather all record fields and make an ap *)
          let sig_ = is_type ctx sig_'' in
          match sig_ with
          | Error _ as e -> check_decls ctx (e :: acc) ts
          | Ok sig_ -> (
              let ctx = bind_func ~id:n ~t:(to_val ctx.env sig_) ctx in
              let ctx, fs = check_assoc ctx [] fs in
              match combine_errors fs with
              | Error _ as e -> check_decls ctx (e :: acc) ts
              | Ok fs ->
                  let csig = List.fold_left (fun acc (_, n) -> Pi (n, acc)) sig_ fs in
                  let ctx = bind_func ~id:cons ~t:(to_val ctx.env csig) ctx in
                  let r = (loc, (n, Record (cons, sig_, fs))) in
                  let ctx =
                    (* we hold the record information for checking Ast.RCons and Ast.RUpdate *)
                    let fs = List.map (fun (i, t) -> (i, to_val ctx.env t)) fs in
                    { ctx with records = (n, cons, sig_'', fs) :: ctx.records }
                  in
                  check_decls ctx (Ok r :: acc) ts))
    in
    let ctx, tdecls = check_decls ctx [] tdecls in
    let@ tdecls = combine_errors tdecls in
    (tdecls, ctx)
  in
  let* ctx =
    let rec go ctx = function
      | [] -> Ok ctx
      | (i, t) :: ts ->
          (*NOTE: 
            inferring here allows you to have a type signature that includes a record, but fails on basic types like Int. 
              - it means that the actual type of the record is given, but the type of primitive (PUni) is given.
            checking if it's a type allows basic types, but fails on records. 
              - it means that the basic type is given, but the actual type of the record is discarded for its identifier.
          *)
          let* t = is_type ctx t in
          let t' = to_val ctx.env t in
          go (bind_func ~id:i ~t:t' ctx) ts
    in
    let decs = List.filter_map (function _, Ast.Dec (i, t) -> Some (i, t) | _ -> None) defs in
    go ctx decs
  in
  let@ defs =
    let defs =
      List.filter_map
        (function
          | loc, Ast.Def (i, as_, wb, b, wb') -> Some (loc, (i, as_, wb, b, wb')) | _ -> None)
        defs
    in
    let rec go ctx acc = function
      | [] -> acc
      | d :: ds -> (
          match check_definition ctx d with
          | Error _ as e -> go ctx (e :: acc) ds
          | Ok (d, ctx) -> go ctx (Ok d :: acc) ds)
    in
    go ctx [] defs |> combine_errors
  in
  (n, mods, tdecls, List.rev defs |> List.flatten)


(* pretty printing *)
let rec pp_ty_decl out ((_, (i, t)) : located_ty_decl) =
  match t with
  | Alias _ -> Format.fprintf out "(ty@[<v>pe %s %a@])" i pp_tdecl_type t
  | _ -> Format.fprintf out "(ty@[<v>pe %s@,%a@])" i pp_tdecl_type t


and pp_tdecl_type out (t : tdecl_type) =
  let pp_field out (i, t) = Format.fprintf out "(%s %a)" i pp_tm t in
  match t with
  | Alias t -> pp_tm out t
  | Record (cons, tsig, r) ->
      Format.fprintf out "(re@[<v>cord %s { %a }@,%a@])" cons pp_tm tsig
        Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out "@,") pp_field)
        r
  | Variant (tsig, v) ->
      Format.fprintf out "(va@[<v>riant { %a }@,%a@])" pp_tm tsig
        Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out "@,") pp_field)
        v


let pp_when_block out (when_block : tm) = Format.fprintf out "(when @[<hov>%a@])" pp_tm when_block

let pp_definition out ((_, (t, f, when_block, body)) : located_definition) =
  Format.fprintf out "de@[<v>f %s { %a } %a@,%a@]@.@." f pp_tm t pp_when_block when_block pp_tm
    body


let pp_module out (mod_name : string) = Format.fprintf out "(module %s)" mod_name

let pp_program out ((prog_name, imports, types, body) : program) =
  Format.fprintf out "%a@.@.%a@.@.%a@.@.%a@." pp_module prog_name
    Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out "@.") pp_import)
    imports
    Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out "@.") pp_ty_decl)
    types
    Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out "@.") pp_definition)
    body
