(* variable generators *)
let fresh_pattern_var () : string = "pat$" ^ (fresh_i () |> string_of_int)
let fresh_bind_var () : string = "b$" ^ (fresh_i () |> string_of_int)
let fresh_scrut_var () : string = "c_id$" ^ (fresh_i () |> string_of_int)

(* shows whether the hole is user-made or generated by the compiler for a default case. *)
type hole_info =
  | Actual
  | Placeholder

(* mutable list that holds all of the holes found in source code *)
let holes : (Location.t * hole_info * (val_ * val_)) list ref = ref []
let add_hole v = holes := v :: !holes

let fmt_holes () =
  let pp_hole out (loc, _, v) =
    let pp_t out (b, t) =
      match force b with
      | VMeta _ -> (
        match force t with
        | VMeta _ -> Format.fprintf out "{ couldn't be solved }"
        | v -> pp_val out v)
      | v -> pp_val out v
    in
    Format.fprintf out "%a ⇒ %a" Location.pp_location loc pp_t v
  in
  Format.asprintf "Fo@[<v 2>und hole(s):@,%a@]"
    Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out "@,") pp_hole)
    !holes

(* unification result to track substitution. *)
(* inspired by https://github.com/dunhamsteve/newt *)
type u_res = (int * val_) list

let pp_u_res out res =
  let pp_aux out (n, v) =
    Format.fprintf out "%d => %a" n pp_val v
  in Format.fprintf out "{ %a }" Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out "; ") pp_aux) res

(* unification mode. *)
(* this distinguishes between normal unification, and unification that should track substitutions. *)
(* inspired by https://github.com/dunhamsteve/newt *)
type u_mode =
  | Normal
  | Subst

let pp_u_mode out = function
  | Normal -> Format.fprintf out "Normal"
  | Subst -> Format.fprintf out "Substitution"

(* case analysis *)
type constr = string * located_pattern * val_ (* m /? pat, ty *)

and clause =
  constr Snoc.t * located_pattern Snoc.t * Ast.located_expr
(* pattern constraints, remaining patterns and body *)

and problem = {
  clauses : clause list;
  target : val_;
}

(* for debugging *)
let pp_constr out (i, pat, t) = Format.fprintf out "%s /? %s ~ %a" i (pp_pattern pat) pp_val t

let pp_clause out (cs, ps, _, b) =
  let cs, ps = (Snoc.to_list cs, Snoc.to_list ps) in
  Format.fprintf out "(%a), (%s) ⇒ %a"
    Format.(pp_print_list ~pp_sep:(fun out () -> fprintf out ", ") pp_constr)
    cs
    (List.map pp_pattern ps |> String.concat ", ")
    Ast.pp_expr b

